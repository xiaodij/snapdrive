// ── Small controls ───────────────────────────────────────────────────────────

export function Segmented<T extends string>({
  value,
  options,
  onChange,
  label,
}: {
  value: T;
  options: { value: T; label: string }[];
  onChange: (v: T) => void;
  label: string;
}) {
  return (
    <div className="segmented" role="group" aria-label={label}>
      {options.map((o) => (
        <button key={o.value} type="button" aria-pressed={o.value === value} onClick={() => o.value !== value && onChange(o.value)}>
          {o.label}
        </button>
      ))}
    </div>
  );
}

export function Switch({
  checked,
  onChange,
  label,
  disabled = false,
}: {
  checked: boolean;
  onChange: (v: boolean) => void;
  label: string;
  disabled?: boolean;
}) {
  return (
    <span className="switch" style={disabled ? { opacity: 0.4 } : undefined}>
      <input type="checkbox" role="switch" aria-label={label} checked={checked} disabled={disabled} onChange={(e) => onChange(e.target.checked)} />
      <span />
    </span>
  );
}

export function Sheet({ title, onClose, children, left, right }: { title: string; onClose: () => void; children: ReactNode; left?: ReactNode; right?: ReactNode }) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && onClose();
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [onClose]);
  return (
    <div className="sheet-backdrop" onClick={onClose}>
      <div className="sheet" role="dialog" aria-modal="true" aria-label={title} onClick={(e) => e.stopPropagation()}>
        <div className="topbar">
          <div className="side">{left}</div>
          <h1>{title}</h1>
          <div className="side right">
            {right ?? (
              <button className="link-btn" onClick={onClose}>
                Done
              </button>
            )}
          </div>
        </div>
        <div className="content">{children}</div>
      </div>
    </div>
  );
}

/** Object URL for a Blob, revoked when the blob changes or the component unmounts. */
export function useObjectUrl(blob: Blob | undefined | null): string | undefined {
  const [url, setUrl] = useState<string>();
  useEffect(() => {
    if (!blob) {
      setUrl(undefined);
      return;
    }
    const u = URL.createObjectURL(blob);
    setUrl(u);
    return () => URL.revokeObjectURL(u);
  }, [blob]);
  return url;
}

// ── Toasts ───────────────────────────────────────────────────────────────────

const toastStore = createStore<{ id: number; text: string } | null>(null);
let toastSeq = 0;

export function toast(text: string, ms = 2800): void {
  const id = ++toastSeq;
  toastStore.set({ id, text });
  setTimeout(() => toastStore.set((t) => (t?.id === id ? null : t)), ms);
}

export function ToastHost() {
  const t = useStore(toastStore);
  return t ? (
    <div className="toast" role="status">
      {t.text}
    </div>
  ) : null;
}
